--- Checks of the mock itself, where its semantics are subtle.
local T = ...

T.test("mock: CVars survive reload and relog, not a client restart", function(t)
	local w = t:world()
	local c = w:AddPlayer({ name = "Alice", addon = false })
	local api = c.api
	api.C_CVar.RegisterCVar("harkTest", "1")
	t:eq(api.C_CVar.SetCVar("harkTest", 5), true, "SetCVar on a registered CVar")
	t:eq(api.C_CVar.SetCVar("nope", 5), false, "SetCVar on an unknown CVar")
	c:Reload(); c:Logout(); c:Login()
	t:eq(c.api.C_CVar.GetCVar("harkTest"), "5", "after reload and relog (string)")
	c:RestartClient()
	t:eq(c.api.C_CVar.GetCVar("harkTest"), nil, "registered CVar after client restart")
	t:eq(c.api.GetCVar("nameplateShowFriends"), "0", "built-in default")
	c.api.SetCVar("nameplateShowFriends", 1)
	c:RestartClient()
	t:eq(c.api.C_CVar.GetCVar("nameplateShowFriends"), "1", "built-in CVar survives restart")
end)

T.test("mock: macros persist, truncate, cap at 120 and are blocked in combat", function(t)
	local w = t:world()
	local c = w:AddPlayer({ name = "Alice", addon = false })
	local idx = c.api.CreateMacro("HarkData", "INV_Misc_QuestionMark", string.rep("x", 300), false)
	t:eq(idx, 1, "first account macro index")
	c:RestartClient()
	local name, _, body = c.api.GetMacroInfo(c.api.GetMacroIndexByName("HarkData"))
	t:eq(name, "HarkData", "survives restart")
	t:eq(#body, 255, "body truncated")
	t:eq(c.api.GetMacroIndexByName("missing"), 0, "unknown macro index")
	w:SetCombat("Alice", true)
	t:ok(not pcall(c.api.EditMacro, idx, nil, nil, "y"), "EditMacro raises in combat")
	w:SetCombat("Alice", false)
	for i = 2, 120 do c.api.CreateMacro("M" .. i, 1, "", false) end
	t:ok(not pcall(c.api.CreateMacro, "Over", 1, "", false), "121st account macro raises")
	t:eq(select(1, c.api.GetNumMacros()), 120, "account macro count")
end)

T.test("mock: frames read unset fields as nil and IsVisible walks parents", function(t)
	local w = t:world()
	local c = w:AddPlayer({ name = "Alice", addon = false })
	local api = c.api
	local root = api.CreateFrame("Frame")
	local child = api.CreateFrame("Frame", nil, root)
	t:eq(root.clubId, nil, "unset field")
	t:eq(child:IsVisible(), true, "visible child")
	t:eq(api.UIParent:IsVisible(), true, "UIParent visible")
	root:Hide()
	t:eq(child:IsVisible(), false, "hidden parent hides child")
	t:eq(child:GetParent(), root, "GetParent")
	t:eq(root:GetParent(), nil, "root has no parent")
	local cb = api.CreateFrame("CheckButton", nil, root, "UICheckButtonTemplate")
	t:ok(cb.Text ~= nil and cb.Text.SetText ~= nil, "check button template has .Text")
	api.GameTooltip:SetOwner(root, "ANCHOR_RIGHT"); api.GameTooltip:SetText("x"); api.GameTooltip:AddLine("y")
	api.GameTooltip:Show(); api.GameTooltip:Hide()
	t:eq(api.GameTooltip:NumLines(), 1, "tooltip lines")
end)

T.test("mock: timers from before a /reload never fire afterwards", function(t)
	local w = t:world()
	local c = w:AddPlayer({ name = "Alice", addon = false })
	local fired = 0
	c.api.C_Timer.NewTicker(1, function() fired = fired + 1 end)
	c.api.C_Timer.After(3, function() fired = fired + 100 end)
	w:Advance(1.5)
	t:eq(fired, 1, "ticker fired once before reload")
	c:Reload()
	w:Advance(10)
	t:eq(fired, 1, "nothing from the old Lua state fired after reload")
end)
